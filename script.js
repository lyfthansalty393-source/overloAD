let cursor = 0;

// All coordinates belong to a fixed 1920 px artboard. Only a uniform scale
// changes on smaller screens; typography and composition never reflow.
for (const era of archive.eras) {
  const photos = archive.images.filter(photo => photo.year === era.year);
  // Positions use the projected rectangle after the sole X-axis rotation.
  // Adjacent cards share 75% of the smaller card's projected area.
  let previous = null;
  const positions = photos.map((photo, index) => {
    const width = 320 * photo.width / photo.height;
    const height = width * photo.height / photo.width * Math.cos(20 * Math.PI / 180);
    const targetX = 1100 + Math.cos(index * .3) * 320;
    let centerX = targetX;
    let centerY = 150 + height / 2;
    if (previous) {
      const maxStep = Math.min(previous.width, width) * .1;
      centerX = previous.centerX + Math.max(-maxStep, Math.min(maxStep, targetX - previous.centerX));
      const overlapWidth = Math.min(previous.centerX + previous.width / 2, centerX + width / 2)
        - Math.max(previous.centerX - previous.width / 2, centerX - width / 2);
      const overlapHeight = .75 * Math.min(previous.width * previous.height, width * height) / overlapWidth;
      centerY = previous.centerY + (previous.height + height) / 2 - overlapHeight;
    }
    previous = {width, height, centerX, centerY};
    return previous;
  });
  const last = positions.at(-1);
  const height = Math.max(1150, last.centerY + last.height / 2 + 600);
  const section = document.createElement('section');
  section.className = 'era';
  section.id = `era-${era.year}`;
  section.setAttribute('aria-label', `${era.year}년대`);
  section.style.top = `${cursor}px`;
  section.style.height = `${height}px`;
  stage.append(section);
  const chapter = { ...era, top: cursor, height, section };
  chapters.push(chapter);
  const nav = document.createElement('button');
  nav.type = 'button';
  nav.textContent = `${era.year}s`;
  nav.setAttribute('aria-label', `${era.year}년대로 이동`);
  nav.addEventListener('click', () => window.scrollTo({
    top: chapter.top * scale, behavior: reduced.matches ? 'instant' : 'smooth'
  }));
  timeline.append(nav);
  chapter.nav = nav;
  photos.forEach((photo, index) => {
    const position = positions[index];
    const y = cursor + position.centerY - position.height / 2;
    const x = position.centerX - position.width / 2;
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'photo';
    button.style.left = `${x}px`;
    button.style.top = `${y - cursor - (position.width * photo.height / photo.width - position.height) / 2}px`;
    button.style.setProperty('--width', `${position.width}px`);
    button.setAttribute('aria-label', `${photo.label}, ${photo.caption} 확대`);
    const img = document.createElement('img');
    img.src = photo.src;
    img.alt = `${photo.label} · ${photo.caption}`;
    img.width = photo.width;
    img.height = photo.height;
    img.loading = cards.length < 8 ? 'eager' : 'lazy';
    img.decoding = 'async';
    button.append(img);
    button.addEventListener('click', () => openImage(photo, button));
    button.addEventListener('focus', () => showCaption(photo));
    section.append(button);
    cards.push({button, photo, y});
  });
  cursor += height;
}
stage.style.height = `${cursor}px`;

function showCaption(photo) {
  captionTitle.textContent = photo.label;
  captionText.textContent = photo.caption;
}
function resize() {
  scale = innerWidth / 1920;
  document.documentElement.style.setProperty('--scale', scale);
  document.querySelector('#scroll-space').style.height = `${cursor * scale}px`;
  schedule();
}
function render() {
  scheduled = false;
  const position = scrollY / scale;
  stage.style.transform = `scale(${scale}) translateY(${-position}px)`;
  const chapter = chapters.findLast(item => item.top <= position + 60) || chapters[0];
  if (selectedEra !== chapter.year) {
    selectedEra = chapter.year;
    yearTitle.textContent = `${chapter.year}s`;
    eventText.textContent = chapter.event;
    eventText.title = chapter.law;
    document.querySelector('#era-law').textContent = chapter.law;
    for (const item of chapters) {
      item.nav.classList.toggle('active', item === chapter);
      if (item === chapter) item.nav.setAttribute('aria-current', 'true');
      else item.nav.removeAttribute('aria-current');
    }
  }
  const nearest = cards.reduce((best, card) => Math.abs(card.y - position - 450) < Math.abs(best.y - position - 450) ? card : best, cards[0]);
  if (selectedCard !== nearest) {
    selectedCard = nearest;
    showCaption(nearest.photo);
    for (const card of cards) card.button.classList.toggle('in-focus', card === nearest);
  }
}
function schedule() {
  if (!scheduled) { scheduled = true; requestAnimationFrame(render); }
}
function openImage(photo, trigger) {
  lastFocus = trigger;
  enlarged.src = photo.src;
  enlarged.alt = `${photo.label} · ${photo.caption}`;
  enlarged.width = photo.width;
  enlarged.height = photo.height;
  dialog.showModal();
  document.documentElement.classList.add('modal-open');
  back.focus({preventScroll: true});
}
